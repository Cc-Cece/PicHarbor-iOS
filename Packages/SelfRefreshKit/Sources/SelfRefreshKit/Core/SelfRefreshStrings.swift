    public static func translate(_ key: String, localeIdentifier: String = Locale.preferredLanguages.first ?? "zh-Hans") -> String {
        let lang = localeIdentifier.lowercased()
        if lang.hasPrefix("en") {
            return english[key] ?? key
        }
        if lang.hasPrefix("yue") || lang.hasPrefix("zh-hant") || lang.hasPrefix("zh-hk") || lang.hasPrefix("zh-tw") || lang.hasPrefix("zh-mo") {
            return traditionalHK[key] ?? key
        }
        return key
    }

